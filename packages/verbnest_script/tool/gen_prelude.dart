// Regenerates lib/src/prelude.dart from assets/prelude.js.
// Run from packages/verbnest_script: dart run tool/gen_prelude.dart
import 'dart:io';

const header = '''// GENERATED by tool/gen_prelude.dart from assets/prelude.js. Do not edit.
/// The JavaScript runtime that gives scripts `pm`, `console` and a Chai-style
/// `pm.expect` (FR-SCR-002/003). It has no access to files or sockets: the
/// engine is created without any host modules, so everything a script can
/// touch is defined in assets/prelude.js.
''';

String render(String js) {
  if (js.contains("'''")) {
    throw StateError("prelude.js must not contain '''");
  }
  return "${header}const scriptPrelude = r'''$js''';\n";
}

void main() {
  final js = File('assets/prelude.js').readAsStringSync();
  File('lib/src/prelude.dart').writeAsStringSync(render(js));
}
