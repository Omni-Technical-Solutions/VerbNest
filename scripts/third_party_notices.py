#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md from pubspec.lock and the pub cache.

Run `flutter pub get` first so every package is in ~/.pub-cache. The Rust
crates behind fjs are summarised by hand in the header (see `cargo metadata` in
the fjs package's libfjs folder).
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def kind(text: str) -> str:
    t = text.lower()
    for needle, name in [
        ("gnu affero", "AGPL"),
        ("lesser general public", "LGPL"),
        ("gnu general public", "GPL"),
        ("mozilla public license", "MPL"),
        ("apache license", "Apache-2.0"),
    ]:
        if needle in t:
            return name
    if "permission is hereby granted" in t and "merge, publish" in t:
        return "MIT"
    if "redistribution and use" in t:
        return "BSD"
    return "OTHER"


def main() -> int:
    lock = open(os.path.join(ROOT, "pubspec.lock")).read()
    items = re.findall(
        r'^  (\S+):\n    dependency: (\S+)\n    description:\n(?:      .*\n)+?    source: (\w+)\n    version: "([^"]+)"',
        lock,
        re.M,
    )
    rows, bad = [], []
    for name, dep, src, ver in items:
        if src != "hosted":
            continue
        d = os.path.expanduser(f"~/.pub-cache/hosted/pub.dev/{name}-{ver}")
        files = sorted(glob.glob(d + "/LICENSE*") + glob.glob(d + "/COPYING*"))
        lic = open(files[0], errors="ignore").read(6000) if files else ""
        k = kind(lic) if lic else "NO LICENSE FILE"
        rows.append((name, ver, k, dep))
        if k in ("AGPL", "LGPL", "GPL", "MPL", "OTHER", "NO LICENSE FILE"):
            bad.append((name, ver, k))
    out = [
        "# Third-party notices",
        "",
        "VerbNest itself is licensed under the Apache License 2.0 (see `LICENSE` and",
        "`NOTICE`). It is built on the software below, each under its own licence. The",
        "full text of every Dart and Flutter package licence is shown in the app under",
        "Settings, About, Open source licences.",
        "",
        "Generated by `scripts/third_party_notices.py` from `pubspec.lock`.",
        "",
        "## Fonts",
        "",
        "- Inter: SIL Open Font License 1.1 (`apps/verbnest_app/assets/fonts/Inter-LICENSE.txt`).",
        "- JetBrains Mono: SIL Open Font License 1.1 (`apps/verbnest_app/assets/fonts/JetBrainsMono-OFL.txt`).",
        "",
        "## Native code",
        "",
        "- `fjs` (MIT) embeds the QuickJS JavaScript engine through Rust. Its 374 Rust",
        "  crates are licensed MIT or Apache-2.0 (some dual-licensed), BSD-3-Clause,",
        "  Unicode-3.0, Zlib, Unlicense or CC0, with three notes: `allo-isolate` ships an",
        "  Apache-2.0 licence file, `r-efi` is offered under",
        "  MIT or Apache-2.0 (or LGPL-2.1-or-later; VerbNest uses it under MIT), and",
        "  `webpki-roots` is CDLA-Permissive-2.0 (certificate root data).",
        "- `pdfrx` (MIT) bundles PDFium (BSD-3-Clause and Apache-2.0 components).",
        "- SQLite is in the public domain.",
        "",
        f"## Dart and Flutter packages ({len(rows)})",
        "",
        "| Package | Version | Licence |",
        "| --- | --- | --- |",
    ]
    for name, ver, k, _ in sorted(rows):
        out.append(f"| {name} | {ver} | {k} |")
    out.append("")
    path = os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")
    open(path, "w").write("\n".join(out))
    print(f"wrote {path}: {len(rows)} packages")
    if bad:
        print("NEEDS REVIEW:", bad)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
